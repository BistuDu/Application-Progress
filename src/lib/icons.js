/** 把 <span data-icon="search"></span> 替换成对应 SVG。 */
export function paintIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((node) => {
    node.innerHTML = icon(node.dataset.icon, Number(node.dataset.iconSize) || 16);
  });
}
